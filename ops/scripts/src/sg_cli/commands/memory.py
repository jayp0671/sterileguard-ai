"""sg memory: keep ops/memory current for people and agents.

STATE.md is rebuilt only from repo facts (git, reports, migrations, env), never from the clock,
so running sync twice with no changes produces no diff.
"""

from __future__ import annotations

import json
import re
from datetime import date
from pathlib import Path

import typer

from sg_cli import core

app = typer.Typer(no_args_is_help=True)

STATE_HEADER = "<!-- AUTO-GENERATED by sg memory sync, do not edit -->"
URL_VARS = ("WEB_URL", "API_URL", "STAGING_WEB_URL", "STAGING_API_URL")


def _git(root: Path, *args: str) -> str:
    code, out = core.capture(["git", *args], cwd=root)
    return out if code == 0 else ""


def current_sprint(tasks_md: str) -> str:
    match = re.search(r"^Current sprint:\s*(.+)$", tasks_md, re.MULTILINE)
    return match.group(1).strip() if match else "unknown"


def task_rows(tasks_md: str) -> list[list[str]]:
    rows = []
    for line in tasks_md.splitlines():
        if line.startswith("| SG-"):
            rows.append([c.strip() for c in line.strip().strip("|").split("|")])
    return rows


def test_summary(root: Path) -> list[str]:
    path = root / "ops" / "reports" / "test" / "latest.json"
    if not path.exists():
        return ["- no test report yet (ops/reports/test/latest.json)"]
    data = json.loads(path.read_text(encoding="utf-8"))
    suites = data.get("suites", [data]) if isinstance(data, dict) else data
    lines = []
    for s in suites:
        lines.append(
            f"- {s.get('suite', '?')}: {s.get('passed', 0)} passed, {s.get('failed', 0)} failed, "
            f"{s.get('skipped', 0)} skipped ({s.get('commit', '?')})"
        )
    return lines


def latest_migration(root: Path) -> str:
    folder = root / "supabase" / "migrations"
    files = sorted(p.name for p in folder.glob("*.sql")) if folder.exists() else []
    return files[-1] if files else "none"


def last_handoff_next(handoff_md: str) -> str:
    nexts = re.findall(r"^- Next:\s*(.+)$", handoff_md, re.MULTILINE)
    return nexts[-1].strip() if nexts else "see handoff.md"


def build_state(root: Path) -> str:
    mem = root / "ops" / "memory"
    tasks = (mem / "TASKS.md").read_text("utf-8") if (mem / "TASKS.md").exists() else ""
    handoff = (mem / "handoff.md").read_text("utf-8") if (mem / "handoff.md").exists() else ""
    branch = _git(root, "rev-parse", "--abbrev-ref", "HEAD") or "unknown"
    log = _git(root, "log", "-10", "--format=%h|%an|%s")
    out = [STATE_HEADER, "", "# STATE", "", f"- Current sprint: {current_sprint(tasks)}"]
    out += [f"- Branch: {branch}", f"- Latest migration: {latest_migration(root)}"]
    out += ["- Active model: none yet (SG-14)", "- Last autofix: none yet (SG-30)"]
    out += [f"- Next up (from handoff): {last_handoff_next(handoff)}", "", "## Tickets", ""]
    rows = task_rows(tasks)
    out += [f"- {r[0]} {r[3] if len(r) > 3 else ''}: {r[1]}" for r in rows] or ["- none"]
    out += ["", "## Tests", "", *test_summary(root), "", "## Deployed URLs", ""]
    urls = [f"- {v}: {core.env_value(v)}" for v in URL_VARS if core.env_value(v)]
    out += urls or ["- none deployed yet"]
    out += ["", "## Last 10 commits", ""]
    commits = [line.split("|", 2) for line in log.splitlines() if line.count("|") >= 2]
    out += [f"- {h} {a}: {s}" for h, a, s in commits] or ["- none"]
    return "\n".join(out) + "\n"


def sync_state(root: Path) -> bool:
    """Write STATE.md if it changed. Returns True when the file was rewritten."""
    path = root / "ops" / "memory" / "STATE.md"
    content = build_state(root)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    if not core.OPTIONS.dry_run:
        path.write_text(content, encoding="utf-8", newline="\n")
    return True


def format_handoff(day: date, who: str, ticket: str, done: str, nxt: str, gotchas: str) -> str:
    return (
        f"\n## {day.isoformat()} · {who} · {ticket}\n\n"
        f"- Done: {done}\n- Next: {nxt}\n- Gotchas: {gotchas or 'none'}\n"
    )


def next_adr_number(adr_dir: Path) -> int:
    nums = [int(m.group(1)) for p in adr_dir.glob("*.md") if (m := re.match(r"(\d{4})-", p.name))]
    return max(nums, default=0) + 1


def slugify(title: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


def new_adr(root: Path, title: str, today: date | None = None) -> Path:
    adr_dir = root / "docs" / "adr"
    num = next_adr_number(adr_dir)
    path = adr_dir / f"{num:04d}-{slugify(title)}.md"
    template = (adr_dir / "0000-template.md").read_text(encoding="utf-8")
    body = template.replace("NNNN", f"{num:04d}").replace("TITLE", title)
    body = body.replace("YYYY-MM-DD", (today or date.today()).isoformat())
    index = root / "ops" / "memory" / "DECISIONS.md"
    if not core.OPTIONS.dry_run:
        path.write_text(body, encoding="utf-8", newline="\n")
        with index.open("a", encoding="utf-8", newline="\n") as fh:
            fh.write(f"| {num:04d} | [{title}](../../docs/adr/{path.name}) | proposed |\n")
    return path


@app.command("sync", help="Rebuild STATE.md from git, reports, migrations and env.")
def sync() -> None:
    result = core.Result("memory", "sync")
    changed = sync_state(core.repo_root())
    result.data["changed"] = changed
    result.add("STATE.md updated" if changed else "STATE.md already current")
    result.finish()


@app.command("handoff", help="Append an entry to handoff.md.")
def handoff(
    ticket: str = typer.Option(..., "--ticket", prompt=True),
    done: str = typer.Option(..., "--done", prompt=True),
    nxt: str = typer.Option(..., "--next", prompt=True),
    gotchas: str = typer.Option("", "--gotchas", prompt=True, prompt_required=False),
    who: str = typer.Option("", "--who", help="Defaults to git user.name."),
) -> None:
    result = core.Result("memory", "handoff")
    root = core.repo_root()
    who = who or _git(root, "config", "user.name") or "unknown"
    entry = format_handoff(date.today(), who, ticket, done, nxt, gotchas)
    if not core.OPTIONS.dry_run:
        with (root / "ops" / "memory" / "handoff.md").open(
            "a", encoding="utf-8", newline="\n"
        ) as f:
            f.write(entry)
    result.add(entry.strip())
    result.finish()


adr_app = typer.Typer(no_args_is_help=True)
app.add_typer(adr_app, name="adr", help="Architecture decision records.")


@adr_app.command("new", help="Create the next numbered ADR from the template.")
def adr_new(title: str) -> None:
    result = core.Result("memory", "adr-new")
    path = new_adr(core.repo_root(), title)
    result.data["path"] = str(path)
    result.add(f"created {path.relative_to(core.repo_root())}")
    result.finish()


task_app = typer.Typer(no_args_is_help=True)
app.add_typer(task_app, name="task", help="Edit the TASKS.md mirror of ClickUp.")


def _tasks_path() -> Path:
    return core.repo_root() / "ops" / "memory" / "TASKS.md"


@task_app.command("add")
def task_add(ticket: str, title: str, lead: str = "", status: str = "to do") -> None:
    result = core.Result("memory", "task-add")
    line = f"| {ticket} | {title} | {lead} | {status} | |\n"
    if not core.OPTIONS.dry_run:
        with _tasks_path().open("a", encoding="utf-8", newline="\n") as fh:
            fh.write(line)
    result.add(line.strip())
    result.finish()


def mark_done(tasks_md: str, ticket: str, pr: str) -> str:
    lines = []
    for line in tasks_md.splitlines():
        if line.startswith(f"| {ticket} |"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            cells += [""] * (5 - len(cells))
            cells[3], cells[4] = "done", pr or cells[4]
            line = "| " + " | ".join(cells[:5]) + " |"
        lines.append(line)
    return "\n".join(lines) + "\n"


@task_app.command("done")
def task_done(ticket: str, pr: str = "") -> None:
    result = core.Result("memory", "task-done")
    path = _tasks_path()
    updated = mark_done(path.read_text(encoding="utf-8"), ticket, pr)
    if not core.OPTIONS.dry_run:
        path.write_text(updated, encoding="utf-8", newline="\n")
    result.add(f"{ticket} marked done")
    result.finish()
